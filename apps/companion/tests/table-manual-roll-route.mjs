import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const source=fs.readFileSync(new URL('../scene-manual-integration.js',import.meta.url),'utf8');
const context={window:{},Scene:{tablePolicy:{mode:'manual'},selectedActor:'a',actors:[{id:'a',name:'Hero',hp:7,ap:3,focus:2,maxHp:10}],version:0},isEnglishPreview:()=>false,activeSceneView:()=> 'gm',canControlSceneActor:()=>true,Logic:{rollXd6:({count})=>({rolls:Array(count).fill(4),successes:count,crits:0})},packets:[]};
context.window.DAWN_TABLE_POLICY={isManual:s=>s.tablePolicy.mode==='manual'};
context.commitSceneEvents=(label,events)=>{context.packets.push({label,events});return {ok:true}};
vm.runInNewContext(source.slice(0,source.indexOf('function openManualTableDice')),context);
const before=JSON.stringify(context.Scene);
assert.ok(context.manualTableRoll(4));
assert.equal(context.packets[0].events[0].type,'table.command');
assert.equal(context.packets[0].events[0].payload.kind,'roll');
assert.equal(context.packets[0].events[0].payload.roll.formula,'4D6');
assert.equal(JSON.stringify(context.Scene),before,'UI submits without writing resources');
assert.equal(context.manualTableRoll(0),null);assert.equal(context.manualTableRoll(31),null);
context.activeSceneView=()=> 'player';context.canControlSceneActor=()=>false;
assert.equal(context.manualTableRoll(4),null,'player cannot roll as another actor');
context.Scene.tablePolicy.mode='rules';assert.equal(context.manualTableRoll(4),null,'stale dialog cannot run in rules mode');
console.log('Manual dice route: typed storage command, bounded pool, ownership, policy and no local resource writes passed');
