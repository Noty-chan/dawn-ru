import assert from 'node:assert/strict';
import {loadHeroModel} from './load-hero-model.mjs';
const model=loadHeroModel();
const hero=model.run('JSON.parse(JSON.stringify(blankHero("lionwing")))');
const roll={at:'12:34',actor:'User Имя',formula:'4D6 ≥3',rolls:[6,3,2,1,5],dice:{threshold:3,criticalAt:5},opposedRequestId:'opposed-qa',count:4,successes:3,crits:2,outcome:'Встречный бросок',target:null,allIn:true,payment:'Влияние, флэшбек +4'};
hero.runtime.diceHistory=[roll];
model.select(hero);
assert.deepEqual(model.snapshot().hero.runtime.diceHistory,[roll],'The actual hero loader retains rendered history fields');
const exported=model.run('JSON.parse(JSON.stringify({format:"dawn-ru-hero",schema:2,hero:S}))');
model.select(exported.hero);
assert.deepEqual(model.snapshot().hero.runtime.diceHistory,[roll],'Portable export/import and subsequent reload preserve names, formulas, faces, thresholds, payment and opposed target');
const old={at:'01:04',count:4,successes:6,crits:2,outcome:'Крайний успех',target:2,allIn:false,payment:''};
hero.runtime.diceHistory=[old];model.select(hero);
let restored=model.snapshot().hero.runtime.diceHistory[0];
for(const [key,value] of Object.entries(old))assert.deepEqual(restored[key],value);
assert.deepEqual(restored.rolls,[]);assert.deepEqual(restored.dice,{threshold:4,criticalAt:6});
hero.runtime.diceHistory=[null,[],false,{...roll,actor:'x'.repeat(900),formula:'D6'.repeat(400),rolls:[null,0,7,'6',2.5,6,1],dice:{threshold:99,criticalAt:-3},payment:'x'.repeat(120),unexpected:{secret:'discard'}}];model.select(hero);
restored=model.snapshot().hero.runtime.diceHistory[0];assert.equal(model.snapshot().hero.runtime.diceHistory.length,1);
assert.equal(restored.actor.length,500);assert.equal(restored.formula.length,500);assert.equal(restored.payment.length,80);
assert.deepEqual(restored.rolls,[6,1]);assert.deepEqual(restored.dice,{threshold:6,criticalAt:1});assert.equal(restored.unexpected,undefined);
hero.runtime.diceHistory=Array.from({length:30},()=>({...roll,rolls:Array(400).fill(6)}));model.select(hero);
assert.equal(model.snapshot().hero.runtime.diceHistory.length,20);assert.equal(model.snapshot().hero.runtime.diceHistory[0].rolls.length,300);
console.log('Hero dice history: reload/export retains author, D6 formula, faces, thresholds, opposed badge and payment; old sheets and bounded malformed input pass');
